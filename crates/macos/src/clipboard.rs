//! NSPasteboard access: read/write text, files and images, change detection.

use objc2::rc::Retained;
use objc2::runtime::ProtocolObject;
use objc2_app_kit::{
    NSBitmapImageFileType, NSBitmapImageRep, NSPasteboard, NSPasteboardItem, NSPasteboardTypeFileURL, NSPasteboardTypePNG,
    NSPasteboardTypeString, NSPasteboardTypeTIFF, NSPasteboardWriting,
};
use objc2_foundation::{NSArray, NSData, NSDictionary, NSString, NSURL};
use std::path::PathBuf;

/// Content currently on the pasteboard.
#[derive(Debug, Clone, PartialEq)]
pub enum ClipContent {
    Text(String),
    Files(Vec<PathBuf>),
    /// PNG bytes + size.
    Image {
        png: Vec<u8>,
        width: u32,
        height: u32,
    },
}

fn pb() -> Retained<NSPasteboard> {
    NSPasteboard::generalPasteboard()
}

/// Monotonic counter that changes whenever the pasteboard content changes.
pub fn change_count() -> isize {
    pb().changeCount()
}

/// Types that mark sensitive/transient data (password managers etc.),
/// see nspasteboard.org.
const IGNORED_TYPES: &[&str] = &[
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
    "com.agilebits.onepassword",
    "com.typeit4me.clipping",
    "de.petermaurer.TransientPasteboardType",
    "Pasteboard generator type",
    "net.antelle.keeweb",
];

/// True if the current pasteboard content should not be recorded.
pub fn is_concealed() -> bool {
    let Some(types) = pb().types() else { return false };
    types.iter().any(|t| {
        let s = t.to_string();
        IGNORED_TYPES.iter().any(|i| s == *i)
    })
}

pub(crate) fn file_url_to_path(s: &str) -> Option<PathBuf> {
    let rest = s.strip_prefix("file://")?;
    let rest = rest.strip_prefix("localhost").unwrap_or(rest);
    // percent-decode
    let bytes = rest.as_bytes();
    let mut out = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' && i + 2 < bytes.len() {
            // Slice bytes, not the str: a `%` followed by a multibyte character must not panic.
            if let Some(b) = std::str::from_utf8(&bytes[i + 1..i + 3]).ok().and_then(|h| u8::from_str_radix(h, 16).ok()) {
                out.push(b);
                i += 3;
                continue;
            }
        }
        out.push(bytes[i]);
        i += 1;
    }
    let p = String::from_utf8(out).ok()?;
    if p.is_empty() {
        return None;
    }
    // A file REFERENCE url (`file:///.file/id=<n>.<m>`) is not a path: ask Foundation for the
    // real one. Gone file: nothing, rather than a bogus path every tool would choke on.
    if p.starts_with("/.file/id=") {
        return file_reference_path(s);
    }
    // keep the root: "file:///" must stay "/", never become an empty path
    let trimmed = p.trim_end_matches('/');
    Some(PathBuf::from(if trimmed.is_empty() { "/" } else { trimmed }))
}

/// Real path behind a `file:///.file/id=...` reference url, or `None` when it no longer resolves.
fn file_reference_path(url: &str) -> Option<PathBuf> {
    let url = NSURL::URLWithString(&NSString::from_str(url))?;
    let real = url.filePathURL()?;
    let path = real.path()?.to_string();
    (!path.is_empty() && !path.starts_with("/.file/id=")).then(|| PathBuf::from(path))
}

/// `NSURL` for a file path, or `None` for an empty one: `+[NSURL fileURLWithPath:]` returns NULL
/// for "" and the binding panics on NULL, which crashed the app in a real session.
pub(crate) fn ns_file_url(p: &std::path::Path) -> Option<Retained<NSURL>> {
    let s = p.to_string_lossy();
    if s.is_empty() {
        return None;
    }
    Some(NSURL::fileURLWithPath(&NSString::from_str(&s)))
}

fn png_from_data(data: &NSData) -> Option<(Vec<u8>, u32, u32)> {
    let rep = NSBitmapImageRep::imageRepWithData(data)?;
    let w = rep.pixelsWide() as u32;
    let h = rep.pixelsHigh() as u32;
    let props = NSDictionary::new();
    let png = unsafe { rep.representationUsingType_properties(NSBitmapImageFileType::PNG, &props) }?;
    Some((png.to_vec(), w, h))
}

/// Read the current pasteboard content (files > image > text).
pub fn read() -> Option<ClipContent> {
    let pb = pb();
    unsafe {
        if let Some(items) = pb.pasteboardItems() {
            let files: Vec<PathBuf> = items
                .iter()
                .filter_map(|it| it.stringForType(NSPasteboardTypeFileURL))
                .filter_map(|s| file_url_to_path(&s.to_string()))
                .collect();
            if !files.is_empty() {
                return Some(ClipContent::Files(files));
            }
        }
        let text = pb.stringForType(NSPasteboardTypeString).map(|s| s.to_string());
        for ty in [NSPasteboardTypePNG, NSPasteboardTypeTIFF] {
            if let Some(d) = pb.dataForType(ty) {
                // Prefer text if the image is just a rendering of rich text.
                if text.as_deref().is_some_and(|t| !t.trim().is_empty()) {
                    break;
                }
                if let Some((png, width, height)) = png_from_data(&d) {
                    return Some(ClipContent::Image { png, width, height });
                }
            }
        }
        text.filter(|t| !t.is_empty()).map(ClipContent::Text)
    }
}

/// Replace the pasteboard with plain text.
pub fn write_text(s: &str) {
    let pb = pb();
    pb.clearContents();
    unsafe {
        pb.setString_forType(&NSString::from_str(s), NSPasteboardTypeString);
    }
}

/// Replace the pasteboard with file references.
pub fn write_files(paths: &[PathBuf]) {
    let pb = pb();
    pb.clearContents();
    let urls: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
        paths.iter().filter_map(|p| ns_file_url(p)).map(ProtocolObject::from_retained).collect();
    let arr = NSArray::from_retained_slice(&urls);
    pb.writeObjects(&arr);
}

/// Replace the pasteboard with a PNG image.
pub fn write_png(png: &[u8]) {
    let pb = pb();
    pb.clearContents();
    let data = NSData::with_bytes(png);
    unsafe {
        pb.setData_forType(Some(&data), NSPasteboardTypePNG);
        // Also provide TIFF for apps that don't read PNG.
        if let Some(rep) = NSBitmapImageRep::imageRepWithData(&data) {
            if let Some(tiff) = rep.TIFFRepresentation() {
                pb.setData_forType(Some(&tiff), NSPasteboardTypeTIFF);
            }
        }
    }
}

pub fn write(content: &ClipContent) {
    match content {
        ClipContent::Text(t) => write_text(t),
        ClipContent::Files(f) => write_files(f),
        ClipContent::Image { png, .. } => write_png(png),
    }
}

/// Plain text currently on the pasteboard.
pub fn read_text() -> Option<String> {
    unsafe { pb().stringForType(NSPasteboardTypeString).map(|s| s.to_string()) }
}

/// Full copy of the pasteboard (every item and type, including privacy markers).
pub struct Snapshot(Vec<Vec<(String, Vec<u8>)>>);

pub fn snapshot() -> Snapshot {
    let mut items = vec![];
    if let Some(list) = pb().pasteboardItems() {
        for it in list.iter() {
            let mut formats = vec![];
            for t in it.types().iter() {
                if let Some(d) = it.dataForType(&t) {
                    formats.push((t.to_string(), d.to_vec()));
                }
            }
            items.push(formats);
        }
    }
    Snapshot(items)
}

/// Restore a snapshot exactly, keeping concealed/transient type markers.
pub fn restore(s: &Snapshot) {
    let pb = pb();
    pb.clearContents();
    let items: Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>> =
        s.0.iter()
            .map(|formats| {
                let item = NSPasteboardItem::new();
                for (ty, bytes) in formats {
                    item.setData_forType(&NSData::with_bytes(bytes), &NSString::from_str(ty));
                }
                ProtocolObject::from_retained(item)
            })
            .collect();
    if !items.is_empty() {
        pb.writeObjects(&NSArray::from_retained_slice(&items));
    }
}

#[cfg(test)]
mod tests {

    /// A drag from Finder can carry a file REFERENCE url (`file:///.file/id=<n>.<m>`). Taken
    /// literally it is a path without a name or extension that no tool can open (seen in a real
    /// session: `ditto: Cannot get the real path for source '/.file/id=...'`, and the drop wheel
    /// offered only ZIP for a PNG). It must resolve to the real path.
    #[test]
    fn file_reference_urls_resolve_to_the_real_path() {
        let dir = std::env::temp_dir().join(format!("fc-fileref-{}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let file = dir.join("picture one.png");
        std::fs::write(&file, b"x").unwrap();
        let url = NSURL::fileURLWithPath(&NSString::from_str(&file.to_string_lossy()));
        let reference = url.fileReferenceURL().expect("a file reference url for an existing file");
        let text = reference.absoluteString().expect("absolute string").to_string();
        assert!(text.contains("/.file/id="), "test needs a real reference url: {text}");
        let got = file_url_to_path(&text).expect("resolved");
        assert_eq!(std::fs::canonicalize(&got).unwrap(), std::fs::canonicalize(&file).unwrap(), "{text} -> {got:?}");
        assert!(!got.to_string_lossy().contains(".file/id="), "{got:?}");
        // a reference to a file that is gone resolves to nothing instead of a bogus path
        std::fs::remove_file(&file).unwrap();
        assert_eq!(file_url_to_path(&text), None);
        let _ = std::fs::remove_dir_all(&dir);
    }
    use super::*;

    #[test]
    fn a_root_or_empty_file_url_never_gives_an_empty_path() {
        // "file:///" used to lose its only slash and become an empty path, which made
        // +[NSURL fileURLWithPath:] return NULL and panic (seen in the real log)
        assert_eq!(file_url_to_path("file:///"), Some(PathBuf::from("/")));
        assert_eq!(file_url_to_path("file:////"), Some(PathBuf::from("/")));
        assert_eq!(file_url_to_path("file://localhost/"), Some(PathBuf::from("/")));
        assert_eq!(file_url_to_path("file://"), None);
        assert_eq!(file_url_to_path("file://localhost"), None);
        assert_eq!(file_url_to_path("file:///tmp/"), Some(PathBuf::from("/tmp")));
    }

    #[test]
    fn ns_file_url_refuses_an_empty_path_instead_of_panicking() {
        assert!(ns_file_url(std::path::Path::new("")).is_none());
        assert!(ns_file_url(std::path::Path::new("/tmp")).is_some());
        assert!(ns_file_url(std::path::Path::new("relative/name.txt")).is_some());
    }

    #[test]
    fn file_url_decoding_survives_malformed_escapes() {
        assert_eq!(file_url_to_path("file:///tmp/a%20b/"), Some(PathBuf::from("/tmp/a b")));
        // `%a` followed by a two-byte `é`: used to slice inside the character and panic.
        assert_eq!(file_url_to_path("file:///a%aé"), Some(PathBuf::from("/a%aé")));
        assert_eq!(file_url_to_path("file://localhost/x%2"), Some(PathBuf::from("/x%2")));
    }
    #[test]
    fn url_decode() {
        assert_eq!(file_url_to_path("file:///Users/me/My%20File.txt"), Some(PathBuf::from("/Users/me/My File.txt")));
        assert_eq!(file_url_to_path("file:///tmp/dir/"), Some(PathBuf::from("/tmp/dir")));
    }
}

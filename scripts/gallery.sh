#!/bin/bash
# Regenerates every picture of the website gallery (web/public/img/files-<id>.jpg)
# from the app's own screenshot mode (FERROCAST_SCREENSHOT, see dev_screenshot in
# crates/app/src/draw.rs) on generated sample files. Nothing is published.
#
# usage: scripts/gallery.sh            # all pictures
#        scripts/gallery.sh avis crop  # only these ids (size total is then not checked)
#
# Needs (macOS): cargo, ffmpeg + ffprobe (brew install ffmpeg), sips (built in),
#   cupsfilter (built in, makes the sample PDF), perl (built in, watchdog), and
#   either sips or ImageMagick for the JPEG step (sips is used; magick if sips fails).
# Every shot runs with a private FERROCAST_DATA_DIR inside the temp dir, so a
# running Ferrocast (instance lock) and your real data are untouched.
# Dark theme except wheel-convert-light and avis-light. Output 1500x950 JPEG, quality 82,
# total must stay under 3.2 MB.
#
# id                    FERROCAST_VIEW  extra env                               FERROCAST_FILES
# wheel-convert         wheel           WHEEL=convert                           sample.png
# wheel-tools           wheel           WHEEL=tools                             sample.png
# wheel-actions         wheel           WHEEL=actions (7 segments, Zip last)    sample.png
# wheel-convert-light   wheel           WHEEL=convert THEME=light               sample.png
# wheel-tools-video     wheel           WHEEL=tools (9 labelled segments)       sample.mp4
# vtrim vsnapshot vsplit  same name     -                                       sample.mp4
# vcrop vspeed          same name       -                                       sample.mp4
# vredact               vredact         three areas built in                    sample.mp4
# atrim anorm achan     same name       -                                       sample.mp3
# avis                  avis            -                                       sample.mp3
# avis-light            avis            THEME=light                             sample.mp3
# bleep                 bleep           three ranges built in                   sample.mp3
# compress-image        compress        -                                       photo.png (noisy, large)
# compress-video        compress        KB=2048                                 sample.mp4
# meta                  meta            -                                       tagged.mp4
# reorder               reorder         -                                       sample.pdf:second.pdf
# crop edit redact frame annotate  same name -                                  sample.png
# collage               collage         -                                       sample.png:b.png:c.png
# organize              organize        -                                       sample.pdf (3 pages)
set -u
cd "$(dirname "$0")/.." || exit 1
ROOT=$PWD
OUT=$ROOT/web/public/img
LIMIT=3200000

need() { command -v "$1" >/dev/null 2>&1 || { echo "gallery.sh: '$1' is required but not found. $2" >&2; exit 2; }; }
need cargo "Install Rust (https://rustup.rs)."
need ffmpeg "Install it with: brew install ffmpeg"
need ffprobe "Install it with: brew install ffmpeg"
need sips "This script needs macOS."
need cupsfilter "This script needs macOS (it makes the sample PDF)."
need perl "Needed for the per-shot time limit."

echo "== building the app"
cargo build -p ferrocast || { echo "gallery.sh: cargo build failed" >&2; exit 1; }
BIN=$ROOT/target/debug/ferrocast
[ -x "$BIN" ] || { echo "gallery.sh: $BIN missing" >&2; exit 1; }

T=$(mktemp -d /tmp/ferrocast-gallery.XXXXXX)
trap 'rm -rf "$T"' EXIT
S=$T/samples; P=$T/png; mkdir -p "$S" "$P" "$T/data"
FF="ffmpeg -v error -y"

echo "== sample files in $S"
$FF -f lavfi -i "testsrc2=size=1600x1000:rate=1" -frames:v 1 "$S/sample.png" || exit 1
# a noisy copy so the compress window has something real to shrink (PNG of noise is large)
$FF -f lavfi -i "testsrc2=size=1600x1000:rate=1,noise=alls=25:allf=t" -frames:v 1 "$S/photo.png" || exit 1
$FF -f lavfi -i "mandelbrot=size=1200x800:rate=1" -frames:v 1 "$S/b.png" || exit 1
$FF -f lavfi -i "smptehdbars=size=1200x800:rate=1" -frames:v 1 "$S/c.png" || exit 1
VSRC=(-f lavfi -i "testsrc=size=640x360:rate=25:duration=6" -f lavfi -i "sine=frequency=440:duration=6")
$FF "${VSRC[@]}" -c:v libx264 -pix_fmt yuv420p -c:a aac -shortest "$S/sample.mp4" || exit 1
$FF "${VSRC[@]}" -c:v libx264 -pix_fmt yuv420p -c:a aac -shortest \
  -metadata artist="Sample Artist" -metadata title="Test pattern" -metadata comment="Generated by scripts/gallery.sh" "$S/tagged.mp4" || exit 1
# a tone with a slow tremolo so the waveform has some shape
$FF -f lavfi -i "sine=frequency=330:duration=6" -af "tremolo=f=1.2:d=0.9" -c:a libmp3lame -q:a 4 "$S/sample.mp3" || exit 1
# 3-page PDF: text with form feeds, rendered by cups
printf 'Page one\n\nSample document for the Ferrocast gallery.\f\nPage two\n\nSecond page.\f\nPage three\n\nThird page.\n' > "$T/doc.txt"
cupsfilter "$T/doc.txt" > "$S/sample.pdf" 2>/dev/null
printf 'Second file\n\nAnother PDF to merge.\n' > "$T/second.txt"
cupsfilter "$T/second.txt" > "$S/second.pdf" 2>/dev/null
[ -s "$S/sample.pdf" ] && [ -s "$S/second.pdf" ] || { echo "gallery.sh: cupsfilter produced no PDF" >&2; exit 1; }

# shot <id> <input files joined by :> VAR=value ...   (view defaults to the id)
shot() {
  local id=$1 files=$2; shift 2
  local view=$id
  local png=$P/$id.png
  case $id in
    wheel-*) view=wheel ;;
    avis-light) view=avis ;;
  esac
  local try
  for try in 1 2 3; do   # a launch occasionally ends without a picture; retry
    rm -f "$png"
    FERROCAST_DATA_DIR=$T/data/$id.$try \
    perl -e 'alarm 40; exec @ARGV' scripts/shot.sh "$png" FERROCAST_VIEW="$view" FERROCAST_FILES="$files" FERROCAST_THEME=dark "$@" >/dev/null 2>&1
    [ -s "$png" ] && break
  done
  [ -s "$png" ] || { echo "gallery.sh: no screenshot for $id" >&2; return 1; }
}

W() { echo "$S/$1"; }
declare -a IDS=(wheel-convert wheel-tools wheel-actions wheel-convert-light wheel-tools-video
  vtrim vcrop vspeed vsnapshot vsplit vredact atrim anorm achan avis avis-light bleep
  compress-image compress-video meta reorder crop edit redact frame collage organize annotate)
WANT=("$@"); [ ${#WANT[@]} -eq 0 ] && WANT=("${IDS[@]}")

fail=0
for id in "${WANT[@]}"; do
  case $id in
    wheel-convert)       shot $id "$(W sample.png)" FERROCAST_WHEEL=convert ;;
    wheel-tools)         shot $id "$(W sample.png)" FERROCAST_WHEEL=tools ;;
    wheel-actions)       shot $id "$(W sample.png)" FERROCAST_WHEEL=actions ;;
    wheel-convert-light) shot $id "$(W sample.png)" FERROCAST_WHEEL=convert FERROCAST_THEME=light ;;
    wheel-tools-video)   shot $id "$(W sample.mp4)" FERROCAST_WHEEL=tools ;;
    vtrim|vcrop|vspeed|vsnapshot|vsplit|vredact) shot $id "$(W sample.mp4)" ;;
    atrim|anorm|achan|avis|bleep) shot $id "$(W sample.mp3)" ;;
    avis-light)          shot $id "$(W sample.mp3)" FERROCAST_THEME=light ;;
    compress-image)      shot $id "$(W photo.png)" FERROCAST_VIEW=compress ;;
    compress-video)      shot $id "$(W sample.mp4)" FERROCAST_VIEW=compress FERROCAST_KB=2048 ;;
    meta)                shot $id "$(W tagged.mp4)" ;;
    reorder)             shot $id "$(W sample.pdf):$(W second.pdf)" ;;
    crop|edit|redact|frame|annotate) shot $id "$(W sample.png)" ;;
    collage)             shot $id "$(W sample.png):$(W b.png):$(W c.png)" ;;
    organize)            shot $id "$(W sample.pdf)" ;;
    *) echo "gallery.sh: unknown id $id" >&2; fail=1; continue ;;
  esac || fail=1
done

echo "== JPEG 1500x950 q82 into $OUT"
conv() { # png jpg
  if sips -s format jpeg -s formatOptions 82 -z 950 1500 "$1" --out "$2" >/dev/null 2>&1; then return 0; fi
  command -v magick >/dev/null && magick "$1" -background white -flatten -resize 1500x950! -quality 82 "$2"
}
for id in "${WANT[@]}"; do
  [ -s "$P/$id.png" ] || continue
  conv "$P/$id.png" "$OUT/files-$id.jpg" || { echo "gallery.sh: conversion failed for $id" >&2; fail=1; }
done

echo; printf '%-24s %10s\n' id bytes
for f in "$OUT"/files-*.jpg; do
  printf '%-24s %10d\n' "$(basename "$f" .jpg | sed 's/^files-//')" "$(stat -f %z "$f")"
done
total=$(cat "$OUT"/files-*.jpg | wc -c | tr -d ' ')
printf '%-24s %10d (limit %d)\n' TOTAL "$total" "$LIMIT"
[ $fail -eq 0 ] || { echo "gallery.sh: some pictures failed" >&2; exit 1; }
[ "$total" -le "$LIMIT" ] || { echo "gallery.sh: total exceeds $LIMIT bytes" >&2; exit 1; }
echo "ok; PNGs were in $P (deleted on exit)"

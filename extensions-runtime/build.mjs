// Bundles src/main.js (+ react, react-reconciler) into dist/runtime.js, the single file the app
// embeds with include_str!. Run: `npm install && npm run build`, then commit dist/runtime.js.
import { build } from 'esbuild';

await build({
  entryPoints: ['src/main.js'],
  bundle: true,
  platform: 'node',
  target: 'node22',
  format: 'cjs',
  minify: true,
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  outfile: 'dist/runtime.js',
  banner: { js: '// Ferrocast extensions runtime (generated by extensions-runtime/build.mjs; do not edit)\n' },
});

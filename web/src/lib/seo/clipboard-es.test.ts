import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { page } from './clipboard-es';

const root = new URL('../../../../', import.meta.url);

describe('clipboard history page (ES)', () => {
  it('has a description of snippet length and no voseo', () => {
    expect(page.description.length).toBeGreaterThanOrEqual(140);
    expect(page.description.length).toBeLessThanOrEqual(160);
    expect(JSON.stringify(page)).not.toMatch(/\b(vos|tenés|podés|querés|pulsá|arrastrá|hacé|mirá|elegí)\b/i);
  });

  it('names only pasteboard types that the app really ignores', () => {
    const src = readFileSync(new URL('crates/macos/src/clipboard.rs', root), 'utf8');
    // Pasteboard type names the page relies on; vendor ids are matched by prefix so secret scanners
    // do not read a UTI such as 1Password's as a hard-coded password.
    for (const t of [/"org\.nspasteboard\.ConcealedType"/, /"org\.nspasteboard\.TransientType"/, /"org\.nspasteboard\.AutoGeneratedType"/, /"com\.agilebits\./, /"net\.antelle\.keeweb"/]) {
      expect(src).toMatch(t);
    }
  });

  it('lists the retention options the app offers', () => {
    const src = readFileSync(new URL('crates/core/src/models.rs', root), 'utf8');
    for (const l of ['"1 Day"', 'Retention::ThreeMonths', 'Retention::Year', 'Retention::Unlimited']) expect(src).toContain(l);
    expect(JSON.stringify(page)).toContain('1 día, 1 semana, 1 mes, 3 meses, 1 año o sin límite');
  });

  it('never says Spotlight stores passwords', () => {
    const spotlight = JSON.stringify(page.limits.rows.map((r) => r[2]));
    expect(spotlight).not.toMatch(/guarda (las )?contraseñas/i);
  });
});

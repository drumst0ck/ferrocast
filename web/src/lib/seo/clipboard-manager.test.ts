import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { page } from './clipboard-manager';

const root = new URL('../../../../', import.meta.url);

describe('clipboard manager page (EN)', () => {
  it('has a description of snippet length and a cell for every column', () => {
    expect(page.description.length).toBeGreaterThanOrEqual(140);
    expect(page.description.length).toBeLessThanOrEqual(160);
    expect(page.title.length).toBeLessThanOrEqual(65);
    for (const row of page.limits.rows) expect(row).toHaveLength(page.limits.cols.length);
  });

  it('names only pasteboard types that the app really ignores', () => {
    const src = readFileSync(new URL('crates/macos/src/clipboard.rs', root), 'utf8');
    for (const t of [/"org\.nspasteboard\.ConcealedType"/, /"org\.nspasteboard\.TransientType"/, /"org\.nspasteboard\.AutoGeneratedType"/, /"com\.agilebits\./, /"net\.antelle\.keeweb"/]) {
      expect(src).toMatch(t);
    }
  });

  it('lists the retention options the app offers and the controls it ships', () => {
    const models = readFileSync(new URL('crates/core/src/models.rs', root), 'utf8');
    for (const l of ['"1 Day"', '"7 Days"', '"1 Month"', '"3 Months"', '"1 Year"', '"Unlimited"']) expect(models).toContain(l);
    expect(JSON.stringify(page)).toContain('1 day, 7 days, 1 month, 3 months, 1 year or unlimited');
    expect(readFileSync(new URL('crates/app/src/app.rs', root), 'utf8')).toContain('label: "Clear History…"');
  });

  it('only calls sync available from 0.4.0, which the changelog lists as released', () => {
    expect(readFileSync(new URL('CHANGELOG.md', root), 'utf8')).toMatch(/## \[0\.4\.0\][\s\S]*\*\*Sync with iCloud\*\*/);
    expect(JSON.stringify(page)).not.toMatch(/coming in the next version/i);
  });

  it('keeps the unencrypted caveat and never says Spotlight stores passwords', () => {
    expect(JSON.stringify(page)).toMatch(/not encrypted|unencrypted/);
    expect(JSON.stringify(page.limits.rows.map((r) => r[2]))).not.toMatch(/stores? (your )?passwords/i);
    expect(JSON.stringify(page)).not.toMatch(/faster than|lighter than|RAM/i);
  });
});
